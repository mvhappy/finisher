import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import assert from "node:assert/strict";
import { ageDays, fetchCreatedAt, findViolations, isTooYoung, lockfiles, parseLock, parseLocks, resolveDates } from "./check-crate-age.mjs";

const NOW = new Date("2026-11-07T12:00:00Z");
const DAY = 86_400_000;
const ago = (ms) => new Date(NOW.getTime() - ms).toISOString();

const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "fin-core"
version = "0.1.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "1.0.200"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"

[[package]]
name = "svt"
version = "0.2.0"
source = "git+https://example.com/svt#0123456789abcdef"

[[package]]
name = "serde"
version = "0.9.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "def"

[[package]]
name = "other"
version = "1.0.0"
source = "registry+https://example.com/other-index"
`;

test("parseLock keeps only crates.io registry packages, sorted", () => {
  assert.deepEqual(parseLock(LOCK), [
    { name: "serde", version: "0.9.0" },
    { name: "serde", version: "1.0.200" },
  ]);
});

test("ageDays floors to whole days", () => {
  assert.equal(ageDays(ago(7 * DAY), NOW), 7);
  assert.equal(ageDays(ago(7 * DAY - 1), NOW), 6);
  assert.equal(ageDays(ago(0), NOW), 0);
});

test("isTooYoung: exactly N days old passes, one millisecond short fails", () => {
  assert.equal(isTooYoung(ago(7 * DAY), NOW), false);
  assert.equal(isTooYoung(ago(7 * DAY - 1), NOW), true);
  assert.equal(isTooYoung(ago(30 * DAY), NOW), false);
});

test("isTooYoung honours a configured N and treats the future as too young", () => {
  assert.equal(isTooYoung(ago(2 * DAY), NOW, 1), false);
  assert.equal(isTooYoung(ago(2 * DAY), NOW, 3), true);
  assert.equal(isTooYoung(ago(-DAY), NOW, 0.5), true);
  assert.equal(isTooYoung(ago(2 * DAY), NOW, 0), false);
});

test("isTooYoung accepts crates.io fractional-second, offset timestamps", () => {
  assert.equal(isTooYoung("2026-10-01T08:15:30.123456+00:00", NOW), false);
  assert.equal(isTooYoung("2026-11-05T08:15:30.123456+00:00", NOW), true);
  assert.throws(() => isTooYoung("yesterday", NOW), /unparseable/);
});

test("findViolations names young crates and crates without a date", () => {
  const crates = [
    { name: "old", version: "1.0.0" },
    { name: "fresh", version: "2.0.0" },
    { name: "unknown", version: "3.0.0" },
  ];
  const dates = { "old@1.0.0": ago(40 * DAY), "fresh@2.0.0": ago(2 * DAY) };
  const v = findViolations(crates, dates, NOW);
  assert.equal(v.length, 2);
  assert.match(v[0], /^fresh 2\.0\.0: published .* \(2 days ago, need >= 7\)$/);
  assert.match(v[1], /^unknown 3\.0\.0: no publication date$/);
  assert.deepEqual(findViolations(crates, dates, NOW, 1).map((s) => s.split(":")[0]), ["unknown 3.0.0"]);
});

test("resolveDates only fetches what the cache lacks and spaces the lookups", async () => {
  const crates = [
    { name: "a", version: "1.0.0" },
    { name: "b", version: "1.0.0" },
    { name: "c", version: "1.0.0" },
  ];
  const fetched = [];
  const sleeps = [];
  const dates = await resolveDates(crates, { "a@1.0.0": "2020-01-01T00:00:00Z" }, async (n, v) => (fetched.push(`${n}@${v}`), "2021-01-01T00:00:00Z"), {
    delayMs: 250,
    sleep: async (ms) => sleeps.push(ms),
  });
  assert.deepEqual(fetched, ["b@1.0.0", "c@1.0.0"]);
  assert.deepEqual(sleeps, [250]); // one gap between two lookups, none before the first
  assert.equal(dates["a@1.0.0"], "2020-01-01T00:00:00Z");
  assert.equal(dates["c@1.0.0"], "2021-01-01T00:00:00Z");
});

const reply = (status, body, headers = {}) => ({ status, ok: status >= 200 && status < 300, headers: new Map(Object.entries(headers)), json: async () => body });

test("fetchCreatedAt sends a descriptive User-Agent and reads version.created_at", async () => {
  let seen;
  const at = await fetchCreatedAt("serde", "1.0.200", {
    fetchFn: async (url, init) => ((seen = { url, init }), reply(200, { version: { created_at: "2024-05-01T00:00:00Z" } })),
  });
  assert.equal(at, "2024-05-01T00:00:00Z");
  assert.equal(seen.url, "https://crates.io/api/v1/crates/serde/1.0.200");
  assert.equal(seen.init.headers["User-Agent"], "finisher-crate-age-check");
});

test("fetchCreatedAt waits and retries on 429, then fails on other errors", async () => {
  const sleeps = [];
  let calls = 0;
  const at = await fetchCreatedAt("x", "1.0.0", {
    sleep: async (ms) => sleeps.push(ms),
    fetchFn: async () => (++calls === 1 ? reply(429, {}, { "retry-after": "3" }) : reply(200, { version: { created_at: "2024-01-01T00:00:00Z" } })),
  });
  assert.equal(at, "2024-01-01T00:00:00Z");
  assert.deepEqual(sleeps, [3000]);
  await assert.rejects(fetchCreatedAt("x", "1.0.0", { fetchFn: async () => reply(404, {}) }), /HTTP 404/);
  await assert.rejects(fetchCreatedAt("x", "1.0.0", { fetchFn: async () => reply(200, {}) }), /no version\.created_at/);
});

test("lockfiles lists the workspace lock and every committed fuzz lock, in name order", (t) => {
  const root = mkdtempSync(join(tmpdir(), "fin-gate-crate-age-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  for (const c of ["fin-shm", "fin-container", "fin-core"]) mkdirSync(join(root, "crates", c, "fuzz"), { recursive: true });
  writeFileSync(join(root, "crates", "fin-shm", "fuzz", "Cargo.lock"), "");
  writeFileSync(join(root, "crates", "fin-container", "fuzz", "Cargo.lock"), "");
  // fin-core has a fuzz directory but no lock: not listed.
  assert.deepEqual(lockfiles(root), ["Cargo.lock", "crates/fin-container/fuzz/Cargo.lock", "crates/fin-shm/fuzz/Cargo.lock"]);
  assert.deepEqual(lockfiles(join(root, "none")), ["Cargo.lock"]);
});

test("parseLocks merges several locks and drops duplicates", () => {
  const other = LOCK + `\n[[package]]\nname = "libfuzzer-sys"\nversion = "0.4.13"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n`;
  assert.deepEqual(parseLocks([LOCK, other]), [
    { name: "libfuzzer-sys", version: "0.4.13" },
    { name: "serde", version: "0.9.0" },
    { name: "serde", version: "1.0.200" },
  ]);
});
