/** The exit code of an error code, in `fin`'s order: denied, usage, conflict, unavailable, validation, else 6. */
export function exitCodeOf(code: string): number {
  if (DENIED_CODES.includes(code)) return EXIT.denied;
  if (USAGE_CODES.includes(code)) return EXIT.usage;
  if (CONFLICT_CODES.includes(code) || JOB_RESULT_CODES.includes(code)) return EXIT.conflict;
  if (UNAVAILABLE_CODES.includes(code)) return EXIT.unavailable;
  if (VALIDATION_CODES.includes(code)) return EXIT.validation;
  return EXIT.internal;
}
